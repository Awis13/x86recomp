int WriteFlagsTest(const Decoder& dec, const std::string& out, const char* prologue) {
  const std::string pro = prologue;
  const size_t ns = pro.find("namespace recomp::gen {");
  std::string o = pro.substr(0, ns);
  std::string tables;
  char buf[256];
  int pi = 0;
  for (const Source& src : kSources) {
    Program q;
    if (!q.mem.Reserve(32)) return 1;
    q.mem.Commit(src.base, 0x1000, recomp::Prot::RWX);
    Module& m = q.modules.emplace_back();
    m.text_lo = src.base;
    m.text_hi = src.base + src.size;
    for (size_t i = 0; i < src.size; i++) q.mem.write<uint8_t>(src.base + i, src.code[i]);
    for (size_t i = 0; i < src.count; i++) q.entries.insert(src.base + src.entries[i].offset);
    FlagLiveness flags;
    std::string report;
    flags.Run(q, dec, &report);
    for (int opt = 1; opt >= 0; opt--) {
      q.flags = opt ? &flags : nullptr;
      Emitter em(q, dec);
      std::string body;
      std::set<uint64_t> refs;
      EmitStats st;
      for (uint64_t e : q.entries) {
        Function f;
        BuildFunction(q, dec, e, &f);
        em.EmitFunction(f, &body, &refs, &st);
      }
      std::snprintf(buf, sizeof buf, "namespace recomp::gen_%s_%s {", src.name,
                    opt ? "opt" : "ref");
      o += buf + pro.substr(ns + std::string("namespace recomp::gen {").size());
      for (uint64_t e : q.entries) o += "void " + FnName(e) + "(::recomp::Ctx& c);\n";
      o += body + "}\n\n";
      std::snprintf(buf, sizeof buf, "const FlagsFn kFns%d%s[] = {\n", pi, opt ? "opt" : "ref");
      tables += buf;
      for (uint64_t e : q.entries) {
        std::snprintf(buf, sizeof buf, "    {0x%08llXu, &::recomp::gen_%s_%s::%s},\n",
                      (unsigned long long)e, src.name, opt ? "opt" : "ref", FnName(e).c_str());
        tables += buf;
      }
      tables += "};\n";
    }
    // Every function's masks (with the indirect part of ret kept apart).
    std::snprintf(buf, sizeof buf, "const FlagsMask kMasks%d[] = {\n", pi);
    tables += buf;
    for (size_t i = 0; i < src.count; i++) {
      const uint64_t e = src.base + src.entries[i].offset;
      std::snprintf(buf, sizeof buf, "    {\"%s\", 0x%08llXu, 0x%03Xu, 0x%03Xu},\n",
                    src.entries[i].name, (unsigned long long)e, flags.Reads(e),
                    flags.Ret(e) & ~flags.Indirect());
      tables += buf;
    }
    tables += "};\n";
    std::snprintf(buf, sizeof buf, "const uint32_t kAny%d = 0x%03Xu, kIndirect%d = 0x%03Xu;\n",
                  pi, flags.Any(), pi, flags.Indirect());
    tables += buf;
    pi++;
  }
  o += "#include \"lift_flags_forms.h\"\n";
  o += tables;
  o += "extern const FlagsProgram kFlagsPrograms[] = {\n";
  for (int i = 0; i < pi; i++) {
    std::snprintf(buf, sizeof buf,
                  "    {\"%s\", kFns%dopt, kFns%dref, int(sizeof kFns%dopt / sizeof(FlagsFn)), "
                  "kMasks%d, int(sizeof kMasks%d / sizeof(FlagsMask)), kAny%d, kIndirect%d},\n",
                  kSources[i].name, i, i, i, i, i, i, i);
    o += buf;
  }
  std::snprintf(buf, sizeof buf, "};\nextern const int kFlagsProgramCount = %d;\n", pi);
  o += buf;
  FILE* fp = std::fopen(out.c_str(), "wb");
  if (!fp) return 1;
  std::fwrite(o.data(), 1, o.size(), fp);
  std::fclose(fp);
  return 0;
}

